def _resign(record: dict) -> str:
    """Recompute a mutated ROOM_EVENT record's own event_sha256, exactly as
    ``sentinel.room.store._event_sha256`` does, so a tamper test's mutated
    record still passes the digest check and only the deeper check under
    test can catch it."""
    return hashlib.sha256(
        json.dumps({
            "causation_id": record["causation_id"], "correlation_id": record["correlation_id"],
            "event_type": record["event_type"], "payload": record["payload"], "session_id": record["session_id"],
        }, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("utf-8")
    ).hexdigest()


