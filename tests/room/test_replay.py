"""Plan 03 Task 5: offline replay of a frozen room-agent event fixture.

``replay_fixture`` never constructs a provider or drone client -- it only
re-runs the already-recorded event/perception-ingestion stream through the
same store/query projectors live mode uses (``RoomStore``, ``ingest_result``,
``ReadQueries.project``, ``render_answer``). The golden fixture under
``fixtures/room_agent/v1`` is generated by actually running a real
``RoomController`` + ``SafetySupervisor`` session (Fix round 1, Q1) -- takeoff
via checkpoint dispatch, one OBSERVE checkpoint that ingests a single
low-confidence ("uncertain") computer detection, a READ_OBSERVATIONS turn
that reads it back, and the explicit ``ANSWER:<objective>:INCOMPLETE``
candidate, which reports the room's coverage as genuinely incomplete (a
second declared cell has no surveyed view at all in this fixture's site) and
requests a supervisor-owned safe return and landing before completing as
``INCOMPLETE_RETURNED``. Every ``ROOM_EVENT``/``ROOM_CHOICE_ATTEMPT``/
``ROOM_TOOL_OUTCOME`` record and the one ``PERCEPTION_INGESTED`` record are
exactly what that live run produced and persisted -- not hand-authored -- so
the decision records are controller-shaped (real ``state``/``candidates``
snapshots, real causation_id chaining) rather than synthesized.

Plan 03 residual task R (F2): the fixture was regenerated with grounded
counting wired in. Its OBSERVE outcome persists the frame's count evidence
(the detection placed on the floor from the measured pose, flagged
low-confidence), and its terminal answer carries the session COUNT fact
("computer: 0 confirmed; 1 uncertain") that replay re-derives from that
evidence and cross-checks.

Task 3 (closer inspection) is deferred; this fixture never exercises a
closer/validate-by-approach candidate (see the controller ruling at the end
of this plan's task-5 brief).
"""
