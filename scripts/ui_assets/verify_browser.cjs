/* Verify the local review and composition; not a drone/coordinator smoke test. */
const {chromium}=require('playwright');
const fs=require('fs'),path=require('path'),{pathToFileURL}=require('url'),assert=require('assert');
const kit=path.resolve(__dirname,'../../assets/sentinel-ui');
const output=path.resolve(__dirname,'../../artifacts/ui-assets');
const base=process.argv[2]||'http://127.0.0.1:8769';
async function main(){
 fs.mkdirSync(output,{recursive:true});
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const errors=[],badResponses=[],checks=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)badResponses.push(r.url()+' '+r.status())});
 const check=(condition,name)=>{assert(condition,name);checks.push(name)};
 try{
  await page.goto(base+'/review.html',{waitUntil:'networkidle'});
  await page.locator('#brand').waitFor();
  check(await page.locator('.icon-tile').count()===14,'14 original icons render');
  check(await page.locator('#map-host .survey-zone').count()===6,'Six-zone layout renders');
  check(await page.locator('img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)),'All local review images load');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Review has no horizontal overflow at 1440px');
  await page.screenshot({path:path.join(output,'review-brand-1440x900.png')});
  await page.locator('#LEFT_ALLEY_FRONT').focus();await page.keyboard.press('Enter');
  check(await page.locator('#LEFT_ALLEY_FRONT').getAttribute('aria-pressed')==='true','Enter selects zone');
  await page.selectOption('#zone-state','SURVEYED');
  await page.check('#stale-toggle');
  check(await page.locator('#LEFT_ALLEY_FRONT').getAttribute('data-status')==='SURVEYED','Stale preserves survey state');
  check((await page.locator('#freshness-badge').innerText()).startsWith('STALE'),'Stale is separate visible badge');
  await page.selectOption('#layout-mode','route');
  check((await page.locator('#map-host .survey-zone').evaluateAll(z=>z.map(x=>x.id).sort())).join(',')==='LEFT_ALLEY_MIDDLE,RIGHT_ALLEY_MIDDLE','Route-only includes exact two middle zones');
  await page.locator('#LEFT_ALLEY_MIDDLE').focus();await page.keyboard.press('Space');
  check(await page.locator('#LEFT_ALLEY_MIDDLE').getAttribute('aria-pressed')==='true','Space selects zone');
  await page.selectOption('#zone-state','BLOCKED');
  await page.selectOption('#layout-mode','marker');
  check(await page.locator('#LEFT_ALLEY_FRONT').getAttribute('data-status')==='SURVEYED','Changing modes preserves known state');
  check(await page.locator('#LEFT_ALLEY_MIDDLE').getAttribute('data-status')==='BLOCKED','Selected state independent of layout mode');
  await page.locator('#schematic').screenshot({path:path.join(output,'schematic-states.png')});
  await page.check('#marker-toggle');check(await page.locator('#marker-example').isVisible(),'Illustrative marker treatment toggles');
  await page.check('#degraded-toggle');check(await page.locator('#degraded-example').isVisible(),'Degraded banner toggles');
  await page.selectOption('#preflight-demo','failed');
  check(await page.locator('#force-example').isVisible(),'Failed preflight reveals new-run explanation');
  check(await page.locator('#force-example button').isDisabled(),'New-run action stays disabled without coordinator legality');
  await page.selectOption('#preflight-demo','unknown');
  check((await page.locator('.preflight-list strong').allTextContents()).every(x=>x==='Unknown'),'Unknown preflight is not rendered passed');
  await page.selectOption('#preflight-demo','passed');
  await page.locator('#emergency-demo-button').click();
  check(await page.locator('#ordinary-demo').isDisabled(),'Emergency pending disables ordinary control');
  check(await page.locator('#emergency-demo-button').isEnabled(),'Emergency control remains available');
  check((await page.locator('#emergency-demo-status').innerText()).includes('pending'),'Pending acknowledgement is explicit');
  await page.locator('#ack-demo').click();
  check((await page.locator('#emergency-demo-status').innerText()).includes('ACKNOWLEDGED'),'Acknowledged state is explicit');
  await page.locator('#reset-emergency').click();
  check(await page.locator('#ordinary-demo').isEnabled(),'Local reset restores sample control');
  await page.keyboard.press('Shift+Escape');
  check(await page.locator('#ordinary-demo').isDisabled(),'Keyboard emergency fallback works');
  await page.locator('#reset-emergency').click();
  await page.locator('#components').screenshot({path:path.join(output,'component-states.png')});
  await page.goto(base+'/console.html',{waitUntil:'networkidle'});
  const bounds=await page.locator('[data-testid]').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return {id:e.dataset.testid,x:r.x,y:r.y,width:r.width,height:r.height}}));
  check(bounds.length===5&&bounds.every(r=>r.x>=0&&r.y>=0&&r.width>0&&r.height>0&&r.x+r.width<=1440&&r.y+r.height<=900),'All five console regions fit 1440×900');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Console has no horizontal overflow');
  check(await page.locator('.console-header img').evaluate(i=>i.width===40&&i.height===40),'Symbol-only header uses 40px mark');
  check(await page.locator('.console-right').evaluate(e=>e.scrollHeight<=e.clientHeight+1),'Console right panel contents fit their region');
  await page.screenshot({path:path.join(output,'console-study-1440x900.png')});
  await page.keyboard.press('Shift+Escape');
  check((await page.locator('#console-notice').innerText()).includes('STOP REQUEST PENDING'),'Console emergency preview makes no physical claim');
  await page.screenshot({path:path.join(output,'console-emergency-1440x900.png')});
  await page.goto(pathToFileURL(path.join(kit,'review.html')).href,{waitUntil:'load'});
  check(await page.locator('img').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0)),'Direct-file review loads all images');
  await page.selectOption('#layout-mode','route');
  check(await page.locator('#map-host .survey-zone').count()===2,'Direct-file review interactions work without fetch');
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Review has no horizontal overflow at 390px');
  check(errors.length===0,'No browser JavaScript errors');
  check(badResponses.length===0,'No missing HTTP resources');
  const report={status:'passed',checks,console_regions:bounds,errors,bad_responses:badResponses,screenshots:['review-brand-1440x900.png','schematic-states.png','component-states.png','console-study-1440x900.png','console-emergency-1440x900.png']};
  const file=path.join(kit,'validation.json');const validation=JSON.parse(fs.readFileSync(file,'utf8'));validation.browser=report;fs.writeFileSync(file,JSON.stringify(validation,null,2)+'\n');
  console.log(JSON.stringify({browser_checks:checks.length,status:'passed',output},null,2));
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e.stack);process.exitCode=1});
